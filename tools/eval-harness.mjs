#!/usr/bin/env node
// Builds evals/.harness/: a throwaway plugin for `claude plugin eval` that bundles every skill in this
// repository and declares the WebhookVault MCP server, so one suite can test the workflow, general and
// provider skills together. The repository's own plugins carry no MCP server (people connect it with
// their own key), which is why the evals need this wrapper.
//
//   node tools/eval-harness.mjs        rebuild evals/.harness (ignored by git)
//
// The server's URL and key come from EVAL_WEBHOOKVAULT_MCP_URL and EVAL_WEBHOOKVAULT_AGENT_KEY (the
// eval runner passes only EVAL_ variables to its runs). Run it through tools/run-evals.sh.

import { cpSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "evals", ".harness");
// Kept stable: the MCP tool names the graders check are mcp__plugin_<name>_webhookvault__<tool>.
const HARNESS_PLUGIN = "wv";

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, ".claude-plugin"), { recursive: true });

writeFileSync(join(out, ".claude-plugin", "plugin.json"), JSON.stringify({
  name: HARNESS_PLUGIN,
  version: "0.0.0",
  description: "Eval harness for the WebhookVault skills (generated by tools/eval-harness.mjs; not published).",
}, null, 2) + "\n");

writeFileSync(join(out, ".mcp.json"), JSON.stringify({
  mcpServers: {
    webhookvault: {
      type: "http",
      url: "${EVAL_WEBHOOKVAULT_MCP_URL:-https://mcp.webhookvault.net}",
      headers: { Authorization: "Bearer ${EVAL_WEBHOOKVAULT_AGENT_KEY}" },
    },
  },
}, null, 2) + "\n");

cpSync(join(root, "skills"), join(out, "skills"), {
  recursive: true,
  filter: (src) => !/[\\/](node_modules|\.venv|bin|obj|__pycache__)([\\/]|$)/.test(src),
});

// Cases live at evals/<case>/ inside the harness, where `claude plugin eval` looks for them.
cpSync(join(root, "evals", "cases"), join(out, "evals"), { recursive: true });

console.log(`built ${out}`);
